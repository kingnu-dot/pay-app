import { execSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readdirSync, readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { defineConfig } from "vitest/config";
import type { Plugin } from "vite";
import preact from "@preact/preset-vite";

// 外部スクリプトを読み込まず、通信先をルール取得用の API だけに絞る。
// 開発サーバはインラインのスクリプトとスタイルを使うので、本番のビルドにだけ付ける
const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data:",
  "connect-src 'self' https://api.github.com https://overpass-api.de",
  "manifest-src 'self'",
  "worker-src 'self'",
  "base-uri 'self'",
  "form-action 'none'",
].join("; ");

function cspPlugin(): Plugin {
  return {
    name: "inject-csp",
    apply: "build",
    transformIndexHtml(html) {
      return {
        html,
        tags: [
          {
            tag: "meta",
            attrs: { "http-equiv": "Content-Security-Policy", content: CSP },
            injectTo: "head-prepend",
          },
        ],
      };
    },
  };
}

/**
 * 画面に表示する版の識別子（コミットとビルド日時）。配信中のアプリが最新かを確かめるために使う。
 * GitHub Actions では GITHUB_SHA、手元では git から取得する
 */
function buildId(): string {
  let sha = process.env.GITHUB_SHA?.slice(0, 7);
  if (!sha) {
    try {
      sha = execSync("git rev-parse --short=7 HEAD", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
    } catch {
      sha = "unknown";
    }
  }
  return `${sha}（${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC ビルド）`;
}

/** フォルダ内のファイルを、そのフォルダからの相対パス（/ 区切り）で列挙する */
function listFiles(dir: string, base = dir): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    return entry.isDirectory() ? listFiles(full, base) : [relative(base, full).replaceAll("\\", "/")];
  });
}

/**
 * Service Worker（sw.js）をビルド時に生成する。
 * ビルドで出力される全ファイルを端末に保存し、オフラインでも画面を開けるようにする。
 * - ファイルの内容が変わるとキャッシュ名も変わり、次回の起動で新しい版に入れ替わる
 * - 応答の Vary ヘッダは照合で無視する（配信側が付ける Vary のせいで、保存済みのファイルが見つからなくなるため）
 * - 同じオリジンの GET だけを扱う。ルール取得用の API への通信には手を出さない
 */
function serviceWorkerPlugin(): Plugin {
  return {
    name: "generate-service-worker",
    apply: "build",
    enforce: "post",
    generateBundle(_options, bundle) {
      // sw.js のひな形を変えたときは、この文字列も変えてキャッシュ名を更新する
      const hash = createHash("sha256").update("sw-template-2");
      const files = new Set<string>(["index.html"]);
      for (const [name, item] of Object.entries(bundle)) {
        files.add(name);
        hash.update(name).update(item.type === "chunk" ? item.code : item.source);
      }
      for (const name of listFiles("public")) {
        files.add(name);
        hash.update(name).update(readFileSync(join("public", name)));
      }
      const version = hash.digest("hex").slice(0, 16);
      const list = JSON.stringify([...files].sort().map((f) => `./${f}`));
      const source = `// Generated by vite.config.ts. Do not edit.
const CACHE = "pay-app-${version}";
const FILES = ${list};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(FILES.map((f) => new Request(f, { cache: "reload" }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("pay-app-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  if (new URL(request.url).origin !== self.location.origin) return;
  const cached =
    request.mode === "navigate"
      ? caches.match("./index.html", { cacheName: CACHE, ignoreVary: true })
      : caches.match(request, { cacheName: CACHE, ignoreVary: true });
  event.respondWith(cached.then((response) => response ?? fetch(request)));
});
`;
      this.emitFile({ type: "asset", fileName: "sw.js", source });
    },
  };
}

// GitHub Pages のプロジェクトサイト（/pay-app/）で配信するため base を固定する
export default defineConfig({
  base: "/pay-app/",
  plugins: [preact(), cspPlugin(), serviceWorkerPlugin()],
  define: { __BUILD_ID__: JSON.stringify(buildId()) },
  build: {
    target: "es2022",
    sourcemap: false,
  },
  test: {
    include: ["tests/**/*.test.ts"],
    environment: "node",
  },
});
